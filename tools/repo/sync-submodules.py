#!/usr/bin/env python3
"""Regenerates the root .gitmodules from the .gitmodules files of the imported upstream subtrees.

Git only reads the .gitmodules at the repository root, so after `git subtree add/pull` the upstream
submodules (kept as gitlinks inside the subtrees) are invisible to `git submodule`. This script
re-registers every nested submodule at its full path, resolving relative URLs against the upstream
repository URL. The pinned commit stays whatever gitlink the subtree carries.

Usage: python tools/repo/sync-submodules.py [--check]
  --check   exit 1 if the root .gitmodules is out of date (for CI), without writing it.
"""
import configparser
import pathlib
import posixpath
import subprocess
import sys
import urllib.parse

# prefix -> upstream repository URL (must match tools/repo/import-upstreams.sh)
SUBTREES = {
    "common-c": "https://github.com/moonlight-stream/moonlight-common-c.git",
    "host": "https://github.com/LizardByte/Sunshine.git",
    "clients/qt": "https://github.com/moonlight-stream/moonlight-qt.git",
    "clients/android": "https://github.com/moonlight-stream/moonlight-android.git",
    "clients/ios": "https://github.com/moonlight-stream/moonlight-ios.git",
}

HEADER = "# GENERATED by tools/repo/sync-submodules.py from the subtrees' own .gitmodules. Do not edit.\n"


def resolve_url(base: str, url: str) -> str:
    if not url.startswith(("./", "../")):
        return url
    parts = urllib.parse.urlsplit(base)
    # git resolves relative submodule URLs against the superproject URL treated as a directory
    path = posixpath.normpath(posixpath.join(parts.path, "..", url))
    if not path.endswith(".git"):
        path += ".git"
    return urllib.parse.urlunsplit((parts.scheme, parts.netloc, path, "", ""))


def gitlinks(root: pathlib.Path) -> set[str]:
    out = subprocess.run(["git", "ls-files", "-s"], cwd=root, check=True, capture_output=True, text=True).stdout
    return {line.split("\t", 1)[1] for line in out.splitlines() if line.startswith("160000 ")}


def generate(root: pathlib.Path) -> str:
    links = gitlinks(root)
    lines = [HEADER]
    seen = set()
    for prefix, base in SUBTREES.items():
        cfg_path = root / prefix / ".gitmodules"
        if not cfg_path.exists():
            continue
        cfg = configparser.ConfigParser(interpolation=None, strict=False)
        cfg.read_string(cfg_path.read_text(encoding="utf-8"))
        for section in cfg.sections():
            sub = cfg[section]
            if "path" not in sub or "url" not in sub:
                continue
            full = f"{prefix}/{sub['path'].strip()}"
            if full not in links:
                print(f"warning: {full} listed in {prefix}/.gitmodules but has no gitlink; skipped", file=sys.stderr)
                continue
            seen.add(full)
            lines.append(f'[submodule "{full}"]\n')
            lines.append(f"\tpath = {full}\n")
            lines.append(f"\turl = {resolve_url(base, sub['url'].strip())}\n")
            for key in ("branch", "shallow", "ignore"):
                if key in sub:
                    lines.append(f"\t{key} = {sub[key].strip()}\n")
    for orphan in sorted(links - seen):
        print(f"warning: gitlink {orphan} is not described by any subtree .gitmodules", file=sys.stderr)
    return "".join(lines)


def main() -> int:
    root = pathlib.Path(__file__).resolve().parents[2]
    text = generate(root)
    target = root / ".gitmodules"
    current = target.read_text(encoding="utf-8") if target.exists() else ""
    if "--check" in sys.argv[1:]:
        if current != text:
            print(".gitmodules is out of date; run python tools/repo/sync-submodules.py", file=sys.stderr)
            return 1
        return 0
    if current != text:
        target.write_text(text, encoding="utf-8", newline="\n")
        print("updated .gitmodules")
    else:
        print(".gitmodules already up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
